'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const js = fs.readFileSync('assets/ohana-catalogo.js','utf8');
const css = fs.readFileSync('assets/ohana-catalogo.css','utf8');
const html = fs.readFileSync('catalogo-nuovo.html','utf8');
assert(html.includes('id="colorVariant"'), 'Il menu a tendina deve rimanere');
assert(html.includes('id="showAllVariants"'), 'Espansione accessibile mancante');
assert(html.includes('aria-controls="variantPhotos"'));
assert(js.includes('variants.slice(0,6)'), 'La griglia iniziale deve mostrare sei varianti');
assert(js.includes('variantsExpanded?variants:'), 'Espansione completa mancante');
assert(js.includes("openProduct(variant.dataset.variant,true)"), 'Selezione da foto non sincronizzata');
assert(js.includes("openProduct(e.target.value,true)"), 'Selezione dal menu non sincronizzata');
assert(js.includes("variantLabel(v)"), 'Etichetta di colore non controllata');
assert(js.includes("v.colorVerified===true"), 'Non presentare colori incerti come verificati');
assert(js.includes("if(variants.findIndex(v=>v.id===p.id)>=6)variantsExpanded=true"));
assert(css.includes('grid-template-columns:repeat(3,minmax(0,1fr))'));
assert(css.includes('.variant-strip{grid-template-columns:repeat(2,minmax(0,1fr))'));
assert(css.includes('#variantPhotos button[aria-pressed=true]'));
const product=require('../assets/ohana-catalogo.js');
const items=require('../catalogo-nuovo.json').products;
assert(items.length>=5588);
const p=items.find(p=>p.brand==='Jordan'&&p.family==='Air Jordan 1 Mid');
assert(p);
const variants=product.modelVariants(items,p);
assert(variants.length>6);
assert(variants.every(v=>v.brand===p.brand&&v.family===p.family));
console.log('PASS: menu mantenuto, sei varianti, espansione, selezione, colori cautelativi, responsive e catalogo reale.');
